#!/bin/sh
# UserPromptSubmit 훅: 사용자 메시지에 가능 여부 키워드가 있으면 첫 문장에 가능/불가능을 명시하라는 조건부 리마인더를 컨텍스트에 추가
# 질문인지 여부는 셸 패턴으로 판정 불가 - 키워드로 1차 필터 후 판단은 응답 모델에 위임, 준수 여부는 사후 검증 불가

input=$(cat)
prompt=$(printf '%s' "$input" | jq -r '.prompt // empty' 2>/dev/null)

if printf '%s' "$prompt" | grep -qiE '가능|할 수 있|될까|되나|되냐|possible|feasible'; then
  echo "가능 여부 키워드 감지: 사용자가 가능한지 묻는 질문이면 첫 문장에 '가능합니다'/'불가능합니다'(일부만 가능하면 가능한 부분과 불가능한 부분을 각각 명시)를 먼저 답할 것. '어렵습니다'·'제한적입니다' 같은 얼버무림이나 비교표로 시작 금지. 키워드를 언급만 한 메시지(작업 지시 등)면 해당 없음."
fi

exit 0
